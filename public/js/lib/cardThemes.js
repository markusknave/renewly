export function cardThemeFor(label, kind = 'other', network = '') {
	const text = String(label || '').toLowerCase();
	const theme = THEMES.find((candidate) => candidate.match.some((needle) => text.includes(needle)));
	const base = theme || FALLBACKS[kind] || FALLBACKS.other;
	const chosen = CARD_NETWORKS.includes(network) ? network : base.network;
	return { ...base, network: chosen };
}

export function instrumentFor(kind = 'other', instrument = '') {
	if (INSTRUMENTS.includes(instrument)) return instrument;
	if (kind === 'card') return 'debit';
	if (kind === 'bank') return 'account';
	if (kind === 'ewallet') return 'wallet';
	if (kind === 'credit') return 'credit';
	if (kind === 'cash') return 'cash';
	return 'account';
}

export function instrumentLabel(instrument) {
	return INSTRUMENT_LABELS[instrument] || 'Account';
}
